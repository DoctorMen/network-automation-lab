"""The switches in the inventory (decision 0032): what each one's bridge, ports and storm control are, the
script that sets them up (build/<switch>/switch.sh), the names the lab's DNS serves from the same inventory,
and the two levers that take one port's storm control off and put it back (decision 0034).

python -m netlab.switch contain|release <switch>:<port>
"""
from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

import yaml

from . import monitoring
from .inventory import Inventory, load

ROOT = Path(__file__).resolve().parent.parent
BROADCAST = "ff:ff:ff:ff:ff:ff"


def expected(inv: Inventory) -> dict:
    """{switch: {bridge, ports: {port: {vlan, to, role}}, storm_control}}: what the live tests read back."""
    return {name: {"bridge": sw["bridge"], "ports": inv.switch_ports(name), "storm_control": sw.get("storm_control")}
            for name, sw in inv.switches.items()}


def spare_ports(inv: Inventory) -> dict[str, list[str]]:
    """{host: [port]}: a host's ports into a switch that have no address, so they stay down until the host is moved."""
    out: dict[str, list[str]] = {}
    for link in inv.links:
        for ep, other in ((link.a, link.b), (link.b, link.a)):
            if ep.device in inv.hosts and ep.address is None and other.device in inv.switches:
                out.setdefault(ep.device, []).append(ep.interface)
    return out


def render(inv: Inventory, name: str, env) -> str:
    sw = inv.switches[name]
    return env.get_template("switch.sh.j2").render(name=name, bridge=sw["bridge"], ports=inv.switch_ports(name),
                                                   storm=sw.get("storm_control"))


def storm_commands(inv: Inventory, switch: str, port: str, op: str) -> list[list[str]]:
    """The two ebtables commands that add (-A) or delete (-D) one port's storm control, as switch.sh renders them."""
    pps = inv.switches[switch]["storm_control"]["broadcast_pps"]
    match = ["-t", "nat", op, "PREROUTING", "-i", port, "-d", BROADCAST]
    return [["ebtables", *match, "--limit", f"{pps}/sec", "--limit-burst", str(pps), "-j", "ACCEPT"], ["ebtables", *match, "-j", "DROP"]]


def names(inv: Inventory) -> dict[str, str]:
    """{fqdn: address} for every device with an address of its own: a router's loopback, a firewall's inside
    address, a host's address. A switch has none. Generated, never keyed in (OROS FND-4)."""
    zone = inv.raw["dns"]["zone"]
    return {f"{d}.{zone}": monitoring.probe_address(inv, d) for d in inv.devices if d not in inv.switches}


def dns_expected(inv: Inventory) -> dict | None:
    if not inv.raw.get("dns"):
        return None
    return {"zone": inv.raw["dns"]["zone"], "server": monitoring.collector(inv), "names": names(inv)}


def render_dns(inv: Inventory, env, write) -> None:
    """build/noc/hosts.lab and its Corefile: CoreDNS's hosts plugin serves A and PTR records from the file."""
    if not (inv.raw.get("dns") and inv.monitoring):
        return
    noc = monitoring.host(inv)
    lines = ["# Generated by netlab from inventory/network.yml (decision 0032). Do not edit by hand."]
    lines += [f"{address} {fqdn} {fqdn.split('.')[0]}" for fqdn, address in sorted(names(inv).items(), key=lambda x: x[0])]
    write(f"{noc}/hosts.lab", "\n".join(lines) + "\n")
    write(f"{noc}/Corefile", env.get_template("monitoring/Corefile.j2").render(address=monitoring.collector(inv)))
    # The empty root zone every miss falls into: an SOA naming the NOC, no other record, so the answer is NXDOMAIN.
    write(f"{noc}/root.db", f"$ORIGIN .\n@ 3600 IN SOA {noc}.{inv.raw['dns']['zone']}. hostmaster.{inv.raw['dns']['zone']}. 1 7200 3600 1209600 60\n"
                            f"@ 3600 IN NS {noc}.{inv.raw['dns']['zone']}.\n")


def lab_name(build: Path = ROOT / "build") -> str:
    return yaml.safe_load((build / "topology.clab.yml").read_text())["name"]


def contain(inv: Inventory, lab: str, switch: str, port: str, on: bool) -> list[str]:
    """Put one port's storm control back (on) or take it off (release): -A or -D of its two rules, so the rest
    of the switch is untouched and the change is one command away from undone. Returns the commands run."""
    if inv.owner(switch) != inv.operator:
        raise PermissionError(f"{switch} belongs to {inv.owner(switch) or 'nobody we know'}; {inv.operator} can't change it")
    if port not in inv.switch_ports(switch):
        raise KeyError(f"{switch} has no port {port}")
    ran = []
    # Idempotent: each rule is deleted first, so one already there isn't added twice and one already gone is no error.
    for cmd in storm_commands(inv, switch, port, "-D"):
        subprocess.run(["docker", "exec", f"clab-{lab}-{switch}", *cmd], capture_output=True, text=True, timeout=30)
        ran.append(" ".join(cmd))
    if on:
        for cmd in storm_commands(inv, switch, port, "-A"):
            subprocess.run(["docker", "exec", f"clab-{lab}-{switch}", *cmd], capture_output=True, text=True, timeout=30, check=True)
            ran.append(" ".join(cmd))
    return ran


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="netlab.switch")
    p.add_argument("action", choices=["contain", "release"])
    p.add_argument("port", help="<switch>:<port>, such as sw1:eth3")
    p.add_argument("--inventory", default=str(ROOT / "inventory" / "network.yml"))
    args = p.parse_args(argv)
    inv = load(args.inventory)
    try:
        switch, port = args.port.split(":")
        ran = contain(inv, lab_name(), switch, port, on=args.action == "contain")
    except (ValueError, KeyError, PermissionError) as exc:
        print(exc, file=sys.stderr)
        return 1
    print("\n".join(f"{switch}: {c}" for c in ran))
    print(f"{switch}:{port} storm control {'on' if args.action == 'contain' else 'off'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
